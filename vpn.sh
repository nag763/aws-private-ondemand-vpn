#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

REGION="${AWS_REGION:-eu-west-3}"
TFVARS_FILE="$SCRIPT_DIR/terraform.tfvars"
LOCAL_CONF="$SCRIPT_DIR/vpn.conf"
SYS_CONF="/vpn.conf"

usage() {
  cat << "EOF"
Usage: ./vpn.sh <command>

Commands:
  setup   Build the base AMI using Packer and save the AMI ID to terraform.tfvars
  up      Deploy the EC2 instance, save client config to /vpn.conf, and connect
  down    Disconnect from WireGuard and terminate the cloud infrastructure
  clean   Deregister the created AMI and delete its associated EBS snapshot
  help    Show this help message

Examples:
  ./vpn.sh setup
  ./vpn.sh up
  ./vpn.sh down
  ./vpn.sh clean
EOF
}

cmd_setup() {
  echo "=================================================="
  echo " [1/3] Checking prerequisites for AMI build..."
  echo "=================================================="
  if ! command -v packer >/dev/null 2>&1; then
    echo "[ERROR] 'packer' is not installed or not in PATH." >&2
    exit 1
  fi

  echo "Initializing Packer..."
  packer init wireguard.pkr.hcl

  echo "=================================================="
  echo " [2/3] Building AMI with Packer (this may take a few minutes)..."
  echo "=================================================="
  TMP_BUILD_LOG=$(mktemp)
  if ! packer build -color=false wireguard.pkr.hcl 2>&1 | tee "$TMP_BUILD_LOG"; then
    echo "[ERROR] Packer build failed. See output above." >&2
    rm -f "$TMP_BUILD_LOG"
    exit 1
  fi

  echo "=================================================="
  echo " [3/3] Extracting AMI ID and saving configuration..."
  echo "=================================================="
  AMI_ID=$(grep -Eo 'ami-[a-z0-9]{17}' "$TMP_BUILD_LOG" | tail -n 1 || true)
  rm -f "$TMP_BUILD_LOG"

  if [ -z "$AMI_ID" ]; then
    echo "[ERROR] Could not extract newly created AMI ID from Packer output." >&2
    exit 1
  fi

  echo "[+] Discovered new AMI: $AMI_ID"
  cat << EOF > "$TFVARS_FILE"
# Auto-generated by ./vpn.sh setup on $(date)
ami_id = "$AMI_ID"
EOF

  echo "[+] Saved variable to $TFVARS_FILE"
  echo "[+] Setup complete! You can now start your VPN with: ./vpn.sh up"
}

cmd_up() {
  echo "=================================================="
  echo " [1/3] Provisioning VPN instance with Terraform..."
  echo "=================================================="
  if ! command -v terraform >/dev/null 2>&1; then
    echo "[ERROR] 'terraform' is not installed or not in PATH." >&2
    exit 1
  fi

  if [ ! -f "$TFVARS_FILE" ]; then
    echo "[WARN] $TFVARS_FILE not found. Falling back to default AMI configured in main.tf."
    echo "[TIP] Run './vpn.sh setup' if you want to build and use your own AMI."
  fi

  # Initialize Terraform if not initialized yet
  if [ ! -d ".terraform" ]; then
    terraform init
  fi

  # If WireGuard interface is already running locally, tear it down first
  if command -v wg >/dev/null 2>&1 && sudo wg show vpn >/dev/null 2>&1; then
    echo "[!] Active WireGuard connection detected. Tearing down existing link..."
    sudo wg-quick down "$SYS_CONF" 2>/dev/null || sudo wg-quick down "$LOCAL_CONF" 2>/dev/null || sudo wg-quick down vpn 2>/dev/null || true
  fi

  TMP_APPLY_LOG=$(mktemp)
  echo "Running terraform apply..."
  if ! terraform apply -auto-approve 2>&1 | tee "$TMP_APPLY_LOG"; then
    echo "[ERROR] Terraform apply failed." >&2
    rm -f "$TMP_APPLY_LOG"
    exit 1
  fi

  echo "=================================================="
  echo " [2/3] Extracting WireGuard client configuration..."
  echo "=================================================="
  # Parse out the client config block between delimiters, removing ANSI and remote-exec prefixes
  sed -r "s/\x1B\[([0-9]{1,3}(;[0-9]{1,3})*)?[mGK]//g" "$TMP_APPLY_LOG" | \
  sed -E 's/^.*\(remote-exec\): //g' | \
  awk '/~~~~~~~~ Copy paste this configuration in your WireGuard client ~~~~~~~~/ {flag=1; next} /~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~/ {flag=0} flag' > "$LOCAL_CONF"
  rm -f "$TMP_APPLY_LOG"

  if [ ! -s "$LOCAL_CONF" ] || ! grep -q "\[Interface\]" "$LOCAL_CONF"; then
    echo "[ERROR] Failed to extract client configuration from Terraform output." >&2
    exit 1
  fi

  chmod 600 "$LOCAL_CONF"
  echo "[+] Client configuration written to $LOCAL_CONF"

  # Write to /vpn.conf as requested
  if sudo tee "$SYS_CONF" < "$LOCAL_CONF" >/dev/null 2>&1; then
    sudo chmod 600 "$SYS_CONF" 2>/dev/null || true
    echo "[+] Client configuration written to $SYS_CONF"
  else
    echo "[WARN] Could not write to $SYS_CONF. Using $LOCAL_CONF."
  fi

  echo "=================================================="
  echo " [3/3] Connecting to VPN..."
  echo "=================================================="
  if command -v wg-quick >/dev/null 2>&1; then
    if [ -f "$SYS_CONF" ]; then
      sudo wg-quick up "$SYS_CONF"
    else
      sudo wg-quick up "$LOCAL_CONF"
    fi
    echo "=================================================="
    echo " [+] VPN is UP and connected!"
    echo "=================================================="
    sudo wg show vpn 2>/dev/null || sudo wg show || true
  else
    echo "[!] 'wg-quick' not found on this machine."
    echo "[+] Configuration saved to $LOCAL_CONF and $SYS_CONF. Import it into your WireGuard client."
  fi
}

cmd_down() {
  echo "=================================================="
  echo " [1/2] Disconnecting from WireGuard..."
  echo "=================================================="
  if command -v wg-quick >/dev/null 2>&1; then
    sudo wg-quick down "$SYS_CONF" 2>/dev/null || sudo wg-quick down "$LOCAL_CONF" 2>/dev/null || sudo wg-quick down vpn 2>/dev/null || true
  fi

  # Clean up local sensitive configs
  rm -f "$LOCAL_CONF"
  sudo rm -f "$SYS_CONF" 2>/dev/null || true
  echo "[+] VPN link stopped and credentials removed from disk."

  echo "=================================================="
  echo " [2/2] Destroying cloud infrastructure..."
  echo "=================================================="
  if command -v terraform >/dev/null 2>&1; then
    terraform destroy -auto-approve
  fi
  echo "[+] Cloud resources terminated."
}

cmd_clean() {
  echo "=================================================="
  echo " Destroying AMI and associated storage..."
  echo "=================================================="
  if ! command -v aws >/dev/null 2>&1; then
    echo "[ERROR] 'aws' CLI is required to delete the AMI." >&2
    exit 1
  fi

  TARGET_AMI=""
  if [ -f "$TFVARS_FILE" ]; then
    TARGET_AMI=$(grep -E '^\s*ami_id\s*=' "$TFVARS_FILE" | awk -F'"' '{print $2}' || true)
  fi

  if [ -z "$TARGET_AMI" ]; then
    echo "[*] No ami_id found in $TFVARS_FILE. Searching for wg-ami-* in account..."
    TARGET_AMI=$(aws ec2 describe-images --owners self --region "$REGION" --filters "Name=name,Values=wg-ami-*" --query "Images[0].ImageId" --output text 2>/dev/null || true)
  fi

  if [ -z "$TARGET_AMI" ] || [ "$TARGET_AMI" = "None" ]; then
    echo "[!] No AMI found to clean up."
    rm -f "$TFVARS_FILE"
    exit 0
  fi

  echo "[+] Target AMI to destroy: $TARGET_AMI"

  # Find snapshots backing this AMI
  SNAPSHOT_IDS=$(aws ec2 describe-images --image-ids "$TARGET_AMI" --region "$REGION" --query "Images[0].BlockDeviceMappings[*].Ebs.SnapshotId" --output text 2>/dev/null || true)

  echo "[+] Deregistering AMI $TARGET_AMI..."
  aws ec2 deregister-image --image-id "$TARGET_AMI" --region "$REGION"

  if [ -n "$SNAPSHOT_IDS" ] && [ "$SNAPSHOT_IDS" != "None" ]; then
    for SNAP in $SNAPSHOT_IDS; do
      echo "[+] Deleting associated EBS snapshot: $SNAP..."
      aws ec2 delete-snapshot --snapshot-id "$SNAP" --region "$REGION" || true
    done
  fi

  rm -f "$TFVARS_FILE"
  echo "[+] Cleanup complete. $TFVARS_FILE removed."
}

ACTION="${1:-help}"
case "${ACTION,,}" in
  setup)
    cmd_setup
    ;;
  up)
    cmd_up
    ;;
  down)
    cmd_down
    ;;
  clean)
    cmd_clean
    ;;
  help|--help|-h)
    usage
    ;;
  *)
    echo "Unknown command: $1" >&2
    echo ""
    usage
    exit 1
    ;;
esac
